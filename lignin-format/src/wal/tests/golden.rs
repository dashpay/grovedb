const TEXT: &[u8] = b"a value too long for its cell";

/// The value the cell in slot 1 of page 7 has before the first commit.
fn old_pointer() -> ValuePointer {
    pointer(12, 20, 300)
}

/// What the first commit does to page 7: the cell in slot 1 gets a new
/// value hash, and the place of its value is the pending value `place`.
fn cell_run(place: PendingValue) -> Vec<u8> {
    let mut run = Vec::new();
    let mut writer = DeltaRunWriter::new(page(7), None, &mut run);
    writer
        .push(&Delta::Hash {
            slot: slot(1),
            field: HashField::Value,
            hash: &[0x55; 32],
        })
        .expect("a record");
    writer
        .push(&Delta::Value {
            slot: slot(1),
            value: CellValue::Pending(place),
        })
        .expect("a record");
    writer.finish().expect("a run");
    run
}

